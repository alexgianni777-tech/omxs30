'use strict';
const assert=require('node:assert/strict');
const {reviewShort,weekdaysUntil}=require('./short-quality');
const idx={above50:false};
const base={name:'TEST',ticker:'TEST.ST',c:100,atrAbs:2,rsi:45,r21:-7,rs21:-5,pctB:0.4,sma20:104,sma50:110,sma200:115,above50:false,vol:1.4,gap:-0.5};
const go = (change={},calendar={})=>reviewShort({...base,...change},idx,'2026-10-22',calendar);
assert.equal(go().status,'WATCH');
assert.ok(go().warnings.includes('RAPPORTDATUM_EJ_VERIFIERAT'));
assert.equal(go({rsi:32}).status,'BLOCKED');
assert.ok(go({rsi:32}).reasons.includes('OVERSALD_RSI'));
assert.ok(go({gap:-2.8}).reasons.includes('STORT_NEDGAP_JAGA_INTE'));
assert.ok(go({gap:2.8}).reasons.includes('STORT_UPPGAP_INVANTA_BEKRAFTELSE'));
assert.ok(go({pctB:0.01}).reasons.includes('NARA_NEDRE_BOLLINGER'));
assert.ok(go({r21:1}).reasons.includes('INGEN_21D_NEDTREND'));
assert.ok(go({rs21:1}).reasons.includes('EJ_SVAGARE_AN_INDEX_21D'));
assert.ok(go({c:111}).reasons.includes('EJ_UNDER_SMA50'));
assert.ok(go({atrAbs:null}).reasons.includes('DATA_OFULLSTANDIG'));
assert.equal(weekdaysUntil('2026-10-22','2026-10-29'),5);
assert.equal(weekdaysUntil('2026-10-23','2026-10-26'),1);
assert.equal(weekdaysUntil('2026-10-29','2026-10-22'),null);
assert.ok(go({ticker:'BOL.ST'},{'BOL.ST':'2026-10-29'}).reasons.includes('RAPPORT_INOM_5_HANDELSDAGAR'));
assert.equal(go({ticker:'EXAMPLE.ST'},{'EXAMPLE.ST':'2026-12-01'}).status,'WATCH');
assert.equal(go({ticker:'EXAMPLE.ST'},{'EXAMPLE.ST':'2026-12-01'}).warnings.includes('RAPPORTDATUM_EJ_VERIFIERAT'),false);
assert.ok(go().score>=0 && go().score<=100);
console.log('Short-quality regression tests passed');
